#!/usr/bin/env python3
"""hpacktab.goose: RFC 7541's static table (Appendix A) and Huffman code
(Appendix B), taken from golang.org/x/net/http2/hpack's tables.go and
gen.go (which are generated from the RFC) in the Go module cache.

The code is canonical (codes of one length consecutive, in symbol order,
each length's first code following the last of the length before), which
this checks; the decoder walks it by length with the tables written here.

    python3 scripts/gen_hpack_tables.py [--xnet VERSION]
"""

import argparse
import os
import re
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xnet", default="v0.58.0")
    args = ap.parse_args()
    modcache = subprocess.run(["go", "env", "GOMODCACHE"], capture_output=True, text=True, check=True).stdout.strip()
    d = os.path.join(modcache, "golang.org", "x", f"net@{args.xnet}", "http2", "hpack")
    t = open(os.path.join(d, "tables.go")).read()
    g = open(os.path.join(d, "gen.go")).read()
    codes = [int(x, 16) for x in re.findall(r"0x[0-9a-f]+", t[t.index("var huffmanCodes"):t.index("var huffmanCodeLen")])]
    lens = [int(x) for x in re.findall(r"\b(\d+),", t[t.index("var huffmanCodeLen"):])][:256]
    assert len(codes) == 256 and len(lens) == 256
    codes.append(0x3fffffff)          # EOS, RFC 7541 Appendix B
    lens.append(30)
    order = sorted(range(257), key=lambda s: (lens[s], s))
    code, prev = 0, lens[order[0]]
    first = [0] * 31
    count = [0] * 31
    offset = [0] * 31
    for k, s in enumerate(order):
        L = lens[s]
        code = 0 if k == 0 else (code + 1) << (L - prev)
        if code != codes[s]:
            raise SystemExit(f"the code is not canonical at symbol {s}")
        if count[L] == 0:
            first[L] = code
            offset[L] = k
        count[L] += 1
        prev = L
    ents = re.findall(r'\{Name: "([^"]*)"(?:, Value: "([^"]*)")?\}', g[g.index("var staticTableEntries"):])
    assert len(ents) == 61

    def arr(xs, per=16):
        rows = [", ".join(str(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)]
        return "[\n    " + ",\n    ".join(rows) + ",\n]"

    out = [f"""// http.hpacktab: RFC 7541's static table (Appendix A) and Huffman code
// (Appendix B). Generated by scripts/gen_hpack_tables.py from
// golang.org/x/net {args.xnet}'s http2/hpack tables; do not edit.

namespace http;

// The static table's entries 1 to 61: names, then values ("" for none).
let HPACK_STATIC_NAMES: const u8[:][61] = ["""]
    out.append("    " + ",\n    ".join(f'"{n}"' for n, v in ents) + ",\n];")
    out.append("let HPACK_STATIC_VALUES: const u8[:][61] = [")
    out.append("    " + ",\n    ".join(f'"{v}"' for n, v in ents) + ",\n];")
    out.append("")
    out.append("// Each symbol's code (256 is EOS) and its length in bits.")
    out.append(f"let HUFF_CODE: u32[257] = {arr([hex(c) for c in codes], 8)};")
    out.append(f"let HUFF_LEN: u8[257] = {arr(lens, 24)};")
    out.append("")
    out.append("// The code is canonical: of each length L, HUFF_COUNT[L] codes from")
    out.append("// HUFF_FIRST[L], for the symbols HUFF_SYMS[HUFF_OFFSET[L]..] in order.")
    out.append(f"let HUFF_FIRST: u32[31] = {arr([hex(x) for x in first], 8)};")
    out.append(f"let HUFF_COUNT: u16[31] = {arr(count, 16)};")
    out.append(f"let HUFF_OFFSET: u16[31] = {arr(offset, 16)};")
    out.append(f"let HUFF_SYMS: u16[257] = {arr(order, 16)};")
    with open(os.path.join(ROOT, "hpacktab.goose"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote hpacktab.goose")


if __name__ == "__main__":
    main()
